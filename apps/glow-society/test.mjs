import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
const base=path.dirname(new URL(import.meta.url).pathname);
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const js=fs.readFileSync(path.join(base,'app.js'),'utf8');
const css=fs.readFileSync(path.join(base,'styles.css'),'utf8');
new vm.Script(js,{filename:'app.js'});
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size,'duplicate HTML IDs');
const refs=[...js.matchAll(/el\('([^']+)'\)/g)].map(m=>m[1]);
assert.deepEqual([...new Set(refs.filter(id=>!ids.includes(id)&&id!=='lookStack'))],[],'missing JS referenced IDs');
for (const section of ['discover','explore','studio','community','artists','saved']) assert.ok(ids.includes(section),'missing section: '+section);
for (const region of ['lips','cheeks','eyes','hair','nails']) assert.ok(js.includes("seed('"+region+"',["),'missing catalog group');
assert.match(js,/getUserMedia/,'missing explicit camera activation');
assert.match(js,/URL\.revokeObjectURL/,'missing photo cleanup');
assert.match(js,/\.close\(\)/,'missing landmark teardown');
assert.match(html,/MANUAL OVERLAY/,'missing manually positioned preview disclosure');
assert.match(html,/local demo data/,'missing community privacy label');
assert.equal((css.match(/{/g)||[]).length,(css.match(/}/g)||[]).length,'unbalanced CSS blocks');
console.log('Glow Society static tests passed: JavaScript syntax, DOM references, catalog, privacy labels, camera cleanup and CSS delimiters.');
